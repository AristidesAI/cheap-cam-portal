#!/usr/bin/env python3
"""
cheap-cam-portal — Windows command-line tool.

All Windows .bat files in this folder are thin wrappers around this script.
Subcommands:

  setup                  one-time install: download mediamtx + ffmpeg,
                         prompt for cam config, write .env, render
                         mediamtx.yml, start services, open browser

  start                  launch mediamtx + portal in the background
  stop                   kill them
  regen                  rebuild mediamtx.yml from .env

  install-autostart      create a Startup-folder shortcut so the portal
                         launches every time you log into Windows
  uninstall-autostart    remove that shortcut

Run any subcommand with --help for details.
"""

